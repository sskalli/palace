import JSZip from "jszip";
import { prisma } from "@/lib/prisma";
import { getAuthenticatedUserId, jsonError } from "@/lib/http";
import { buildMarkdownExportEntries } from "@/lib/markdown-export";

export async function GET() {
  const userId = await getAuthenticatedUserId();
  if (!userId) return jsonError("Sign in to export notes.", 401);

  try {
    const notes = await prisma.note.findMany({
      where: { userId, archivedAt: null },
      orderBy: [{ folder: { name: "asc" } }, { title: "asc" }],
      include: {
        folder: { select: { name: true } },
        noteTags: { include: { tag: { select: { name: true } } } },
      },
    });
    const zip = new JSZip();
    zip.file(
      "README.md",
      "# Palace Markdown export\n\nThis archive was generated by Palace. Notes are standard Markdown files with YAML frontmatter and can be opened with any Markdown editor.\n",
    );
    for (const entry of buildMarkdownExportEntries(
      notes.map((note) => ({
        id: note.id,
        title: note.title,
        contentMarkdown: note.contentMarkdown,
        folderName: note.folder?.name ?? null,
        tags: note.noteTags.map(({ tag }) => tag.name),
        createdAt: note.createdAt,
        updatedAt: note.updatedAt,
      })),
    )) {
      zip.file(entry.path, entry.content);
    }

    const archive = await zip.generateAsync({ type: "uint8array" });
    return new Response(archive as BodyInit, {
      headers: {
        "Content-Type": "application/zip",
        "Content-Disposition": 'attachment; filename="palace-notes.zip"',
        "Cache-Control": "no-store",
      },
    });
  } catch (error) {
    console.error("Markdown export failed", error);
    return jsonError("The Markdown export could not be generated.", 500);
  }
}
