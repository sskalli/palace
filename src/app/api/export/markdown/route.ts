import JSZip from "jszip";
import { prisma } from "@/lib/prisma";
import { getAuthenticatedUserId, jsonError } from "@/lib/http";
import { descendantIds } from "@/lib/folder-tree";
import { buildExportFolderPaths, buildMarkdownExportEntries, sanitizeExportSegment } from "@/lib/markdown-export";
import { recordIdSchema } from "@/lib/validation";

function downloadHeaders(filename: string, contentType: string) {
	return {
		"Content-Type": contentType,
		"Content-Disposition": `attachment; filename="${filename.replace(/[^\x20-\x7e]/g, "_")}"; filename*=UTF-8''${encodeURIComponent(filename).replace(/['()*]/g, (character) => `%${character.charCodeAt(0).toString(16)}`)}`,
		"Cache-Control": "no-store",
	};
}

export async function GET(request: Request) {
	const userId = await getAuthenticatedUserId();
	if (!userId) return jsonError("Sign in to export notes.", 401);
	const params = new URL(request.url).searchParams;
	const noteId = params.get("noteId");
	const folderId = params.get("folderId");
	if (
		(noteId !== null && folderId !== null) ||
		(noteId !== null && !recordIdSchema.safeParse(noteId).success) ||
		(folderId !== null && !recordIdSchema.safeParse(folderId).success)
	) {
		return jsonError("Choose a single valid note or folder to export.", 400);
	}

	try {
		if (noteId !== null) {
			const note = await prisma.note.findFirst({
				where: { id: noteId, userId },
				include: { noteTags: { include: { tag: { select: { name: true } } } } },
			});
			if (!note) return jsonError("Note not found.", 404);
			const [entry] = buildMarkdownExportEntries(
				[
					{
						...note,
						folderPath: [],
						tags: note.noteTags.map(({ tag }) => tag.name),
					},
				],
				[],
			);
			return new Response(entry.content, {
				headers: downloadHeaders(entry.path, "text/markdown; charset=utf-8"),
			});
		}

		const folders = await prisma.folder.findMany({
			where: { userId },
			select: { id: true, name: true, parentId: true },
		});
		const root = folderId !== null ? folders.find((folder) => folder.id === folderId) : undefined;
		if (folderId !== null && !root) return jsonError("Folder not found.", 404);
		const selectedIds = root ? new Set([root.id, ...descendantIds(folders, root.id)]) : null;
		const scopedFolders = selectedIds ? folders.filter((folder) => selectedIds.has(folder.id)) : folders;
		const folderPaths = buildExportFolderPaths(
			scopedFolders.map((folder) => ({
				...folder,
				parentId: folder.id === root?.id ? null : folder.parentId,
			})),
			root ? [] : ["README.md"],
		);
		const notes = await prisma.note.findMany({
			where: { userId, archivedAt: null, ...(selectedIds ? { folderId: { in: [...selectedIds] } } : {}) },
			orderBy: [{ folder: { name: "asc" } }, { title: "asc" }, { id: "asc" }],
			include: { noteTags: { include: { tag: { select: { name: true } } } } },
		});
		const zip = new JSZip();
		// Folder exports mirror their tree exactly; the full-account archive keeps its guide.
		if (!root)
			zip.file(
				"README.md",
				"# Palace Markdown export\n\nThis archive was generated by Palace. Notes are standard Markdown files with YAML frontmatter and can be opened with any Markdown editor.\n",
			);
		const directoryPaths = [...folderPaths.values()].map((path) => path.join("/"));
		for (const path of directoryPaths) zip.folder(path);
		for (const entry of buildMarkdownExportEntries(
			notes.map((note) => ({
				id: note.id,
				title: note.title,
				contentMarkdown: note.contentMarkdown,
				folderPath: note.folderId ? (folderPaths.get(note.folderId) ?? []) : [],
				tags: note.noteTags.map(({ tag }) => tag.name),
				createdAt: note.createdAt,
				updatedAt: note.updatedAt,
			})),
			[...directoryPaths, ...(!root ? ["README.md"] : [])],
		))
			zip.file(entry.path, entry.content);

		const archive = await zip.generateAsync({ type: "uint8array" });
		const filename = root ? `${sanitizeExportSegment(root.name, "Folder")}.zip` : "palace-notes.zip";
		return new Response(archive as BodyInit, { headers: downloadHeaders(filename, "application/zip") });
	} catch (error) {
		console.error("Markdown export failed", error);
		return jsonError("The Markdown export could not be generated.", 500);
	}
}
