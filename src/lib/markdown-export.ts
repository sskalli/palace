export type ExportNote = {
  id: string;
  title: string;
  contentMarkdown: string;
  createdAt: Date;
  updatedAt: Date;
  tags: { name: string }[];
  folder: { name: string } | null;
};

export type ExportEntry = { path: string; content: string };

function safeSegment(value: string): string {
  const safe = value
    .normalize("NFKC")
    .replace(/[<>:"/\\|?*\u0000-\u001f]/g, "-")
    .replace(/[. ]+$/g, "")
    .trim();
  return safe && safe !== "." && safe !== ".." && /[^.\-\s]/.test(safe)
    ? safe
    : "Untitled";
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

export function makeMarkdownExport(notes: ExportNote[]): ExportEntry[] {
  const paths = new Set<string>(["readme.md"]);
  const entries = notes.map((note) => {
    const title = note.title.trim() || "Untitled";
    const folder = note.folder ? `${safeSegment(note.folder.name)}/` : "";
    let path = `${folder}${safeSegment(title)}.md`;
    if (paths.has(path.toLowerCase())) {
      path = `${folder}${safeSegment(title)}-${note.id.slice(-6)}.md`;
    }
    paths.add(path.toLowerCase());
    const tags = note.tags.map(({ name }) => `  - ${yamlString(name)}`).join("\n");
    const frontmatter = [
      "---",
      `title: ${yamlString(title)}`,
      "tags:",
      tags || "  []",
      `createdAt: ${note.createdAt.toISOString()}`,
      `updatedAt: ${note.updatedAt.toISOString()}`,
      "---",
    ].join("\n");
    const body = note.contentMarkdown.trim();
    return {
      path,
      content: `${frontmatter}\n\n# ${title}${body ? `\n\n${body}` : ""}\n`,
    };
  });
  return [
    {
      path: "README.md",
      content:
        "# Palace Markdown export\n\nThis archive was generated by Palace. Notes are standard Markdown files with YAML frontmatter.\n",
    },
    ...entries,
  ];
}
