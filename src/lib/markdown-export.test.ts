import { describe, expect, it } from "vitest";
import { makeMarkdownExport } from "./markdown-export";

const baseNote = {
  id: "noteabcdef",
  title: "Weekly / plan",
  contentMarkdown: "Keep going.",
  createdAt: new Date("2026-10-12T00:00:00.000Z"),
  updatedAt: new Date("2026-10-12T01:00:00.000Z"),
  tags: [{ name: "career" }],
  folder: { name: "Work" },
};

describe("makeMarkdownExport", () => {
  it("creates safe folder paths and Markdown with dated YAML frontmatter", () => {
    const [readme, note] = makeMarkdownExport([baseNote]);
    expect(readme.path).toBe("README.md");
    expect(readme.content).toContain("generated by Palace");
    expect(note.path).toBe("Work/Weekly - plan.md");
    expect(note.content).toContain('title: "Weekly / plan"');
    expect(note.content).toContain('  - "career"');
    expect(note.content).toContain("createdAt: 2026-10-12T00:00:00.000Z");
    expect(note.content).toContain("# Weekly / plan\n\nKeep going.");
  });

  it("uses safe fallbacks and disambiguates colliding filenames", () => {
    const entries = makeMarkdownExport([
      { ...baseNote, id: "first123456", title: "../" },
      { ...baseNote, id: "secondabcdef", title: "../" },
      { ...baseNote, id: "third123456", title: "", folder: null },
    ]);
    expect(entries.map((entry) => entry.path)).toEqual([
      "README.md",
      "Work/Untitled.md",
      "Work/Untitled-abcdef.md",
      "Untitled.md",
    ]);
  });
});
